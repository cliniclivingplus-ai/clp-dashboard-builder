-- Copies MicrobiomeRX's schema into CLP Compass's Supabase project, namespaced
-- with an mrx_ prefix so nothing collides with CLP Compass's own tables (it
-- has its own unrelated `patients` table, for instance). This is a straight
-- schema mirror of MicrobiomeRX's live database (read via its PostgREST
-- OpenAPI spec) — column names/types/defaults match the source as closely as
-- could be determined; only foreign keys the source's own API explicitly
-- reported are recreated here, nothing invented.
--
-- Run this once, manually, in the Supabase SQL editor for this project
-- (jtidesyasvaiztbxkcgz, cliniclivingplus) — same as every other migration
-- in this repo, none of which are auto-applied.
--
-- After this runs, a separate script copies the actual row data + the
-- original PDF files from MicrobiomeRX's Storage bucket into these tables
-- and the mrx-reports bucket created below.

