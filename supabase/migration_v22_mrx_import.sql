-- Linking table for a future screen where a coach manually connects a
-- MicrobiomeRX patient record to the matching CLP Compass patient record.
-- Empty for now — MicrobiomeRX has no shared identifier (email/phone/clinic
-- id) with CLP Compass's patients today, so this can't be populated
-- automatically.
create table if not exists mrx_patient_links (
  id uuid primary key default gen_random_uuid(),
  clp_patient_id uuid not null references patients(id) on delete cascade,
  mrx_patient_id uuid not null references mrx_patients(id) on delete cascade,
  linked_at timestamptz default now(),
  linked_by text,
  unique (clp_patient_id, mrx_patient_id)
);

-- Storage bucket for the copied original PDF files (mirrors MicrobiomeRX's
-- own supabase/storage-setup.sql bucket definition).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'mrx-reports',
  'mrx-reports',
  false,
  52428800,
  array['application/pdf']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;
